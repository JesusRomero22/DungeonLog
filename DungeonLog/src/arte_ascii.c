/* Retorna arte prestado por ID. Un ID ajeno al catalogo usa un simbolo neutro. */
const char *arte_enemigo(int id)
{
    switch (id) {
        case 10: return RATA;
        case 20: return MONJE;
        case 30: return ESCRIBA;
        case 40: return CUSTODIO;
        case 50: return CABALLERO;
        case 60: return ESPECTRO;
        case 70: return SOMBRA;
        default: return "                  [?]\n";
    }
}

/* Consulta una sala sin modificarla ni reservar memoria. */
const char *arte_sala(int id)
{
    return id >= 0 && id < TOTAL_SALAS ? SALAS[id] : "";
}

/* Iconos acompanados siempre de nombre/tipo en la interfaz. No usar free. */
const char *arte_icono_objeto(int id)
{
    switch (id) {
        case 1: return "[!]";
        case 2: return "($)";
        case 3: return "\\U/";
        case 4: return "{+}";
        case 5: return "<*>";
        default: return "[?]";
    }
}
